create table if not exists member (
    id uuid primary key,
    email text unique not null,
    password_hash text not null,
    name text not null,
    doc jsonb not null default '{}',
    version bigint not null default 0,
    stream_key uuid not null unique
);

create table if not exists asset (
    id bigint generated by default as identity (start with 1000) primary key,
    owner uuid references member,
    mime text not null
);

create table if not exists outbox (
    id uuid primary key,
    payload text not null
);

create table if not exists notice (
    id uuid primary key,
    recipient uuid references member,
    message text not null,
    created timestamptz default now()
);

create table if not exists chat (
    id bigint generated always as identity primary key,
    channel uuid references member,
    author uuid references member,
    message text not null
);


alter table asset add column if not exists status text not null default 'pending';
alter table asset add column if not exists retired boolean not null default false;
alter table asset add column if not exists uploaded timestamptz not null default now();
create table if not exists play_event (
    id bigint generated always as identity primary key,
    asset bigint references asset on delete cascade,
    viewer text not null,
    created timestamptz not null default now()
);

create index if not exists play_event_asset_time on play_event(asset,created);

alter table asset add column if not exists claim_id uuid;
alter table asset add column if not exists claim_until timestamptz;
